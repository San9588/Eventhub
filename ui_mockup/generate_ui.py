    w = len(label)*5 + 8
    if active:
        rect(x, 52, w, 8, GREEN)
        text(x+4, 54, label, 1, BG)
    else:
        rect(x, 52, w, 8, BG2); d.rectangle([x*U,52*U,(x+w)*U-1,(52+8)*U-1], outline=BORDER)
        text(x+4, 54, label, 1, OFF)
