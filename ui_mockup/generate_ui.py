ICON_POW  = ['...#....','..###...','..#.#...','..#.#...','..#.#...','...#....','.#####..','...#....']

# ---------------------------------------------------------------- canvas
U = 5                      # 1 logical unit = U px
W, H = 100, 200            # logical size
img = Image.new('RGB', (W*U, H*U), BG)
d = ImageDraw.Draw(img)

def rect(x, y, w, h, color):
    d.rectangle([x*U, y*U, (x+w)*U-1, (y+h)*U-1], fill=color)

def text(x, y, s, scale=1, color=GREEN, bg=None):
    for c in s:
        g = FONT.get(c, FONT[' '])
        if bg:
            rect(x, y, 5*scale, 7*scale, bg)
        for gy, row in enumerate(g):
            for gx, ch in enumerate(row):
                if ch == '#':
                    rect(x+gx*scale, y+gy*scale, scale, scale, color)
        x += 5*scale

def icon(imgd, x, y, rows, color, scale=1):
    for gy, row in enumerate(rows):
        for gx, ch in enumerate(row):
            if ch == '#':
                rect(x+gx*scale, y+gy*scale, scale, scale, color)

def toggle(x, y, on):
    # 13x8 unit switch
    if on:
        rect(x, y, 13, 8, (9, 30, 17))
        rect(x+1, y+1, 11, 6, None)
        rect(x+1, y+1, 8, 6, GREEN2)
        rect(x+9, y+2, 3, 4, GREEN)   # knob
    else:
        rect(x, y, 13, 8, (9, 18, 13))
        rect(x+1, y+1, 3, 6, OFF)     # knob
        rect(x+5, y+3, 6, 1, DIM)

def dot(x, y, color, s=3):
    rect(x, y, s, s, color)

