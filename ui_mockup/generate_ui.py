# ---------------------------------------------------------------- pixel icons
ICON_BOLT = ['...##...','..##....','.##.##..','.##..##.','.##..##.','.##..##.','...###..','...##...']
ICON_LIST = ['........','##.##.##','........','##.##.##','........','##.##.##','........','........']
